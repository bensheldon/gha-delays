#!/usr/bin/env python3
"""Generate no-op scheduled workflows covering schedule configurations.

Re-run after editing VARIANTS: `python3 script/generate.py`
"""
import pathlib, shutil

OUT = pathlib.Path(__file__).resolve().parent.parent / ".github" / "workflows"

# (name, [ {cron, timezone?}, ... ])
VARIANTS = []

# 1. Minute sweep: every minute of the hour, hourly. Covers all 24x60 hour/minute slots.
for m in range(60):
    VARIANTS.append((f"minute-{m:02d}", [{"cron": f"{m} * * * *"}]))

# 2. Format variants. Most target minute 17 so they compare against minute-17.
VARIANTS += [
    ("fmt-every-minute",       [{"cron": "* * * * *"}]),
    ("fmt-step-5",             [{"cron": "*/5 * * * *"}]),
    ("fmt-range-step-5",       [{"cron": "0-59/5 * * * *"}]),
    ("fmt-list-5",             [{"cron": ",".join(str(m) for m in range(0, 60, 5)) + " * * * *"}]),
    ("fmt-step-15",            [{"cron": "*/15 * * * *"}]),
    ("fmt-offset-step-15",     [{"cron": "7/15 * * * *"}]),
    ("fmt-list-17-47",         [{"cron": "17,47 * * * *"}]),
    ("fmt-multi-cron-17-47",   [{"cron": "17 * * * *"}, {"cron": "47 * * * *"}]),
    ("fmt-hour-step-1",        [{"cron": "17 */1 * * *"}]),
    ("fmt-hour-range",         [{"cron": "17 0-23 * * *"}]),
    ("fmt-hour-list-even",     [{"cron": "17 " + ",".join(str(h) for h in range(0, 24, 2)) + " * * *"}]),
    ("fmt-dow-numeric",        [{"cron": "17 * * * 0-6"}]),
    ("fmt-dow-names",          [{"cron": "17 * * * SUN-SAT"}]),
    ("fmt-month-names",        [{"cron": "17 * * JAN-DEC *"}]),
    ("fmt-dom-range",          [{"cron": "17 * 1-31 * *"}]),
    ("fmt-tz-utc",             [{"cron": "17 * * * *", "timezone": "UTC"}]),
    ("fmt-tz-new-york",        [{"cron": "17 * * * *", "timezone": "America/New_York"}]),
    ("fmt-tz-kolkata",         [{"cron": "17 * * * *", "timezone": "Asia/Kolkata"}]),  # +05:30: fires at :47 UTC
    ("fmt-tz-kolkata-00",      [{"cron": "0 * * * *", "timezone": "Asia/Kolkata"}]),   # local :00 = :30 UTC
    ("fmt-tz-kathmandu",       [{"cron": "17 * * * *", "timezone": "Asia/Kathmandu"}]),  # +05:45
]

TEMPLATE = """\
# Generated by script/generate.py. Do not edit by hand.
name: {name}
on:
  schedule:
{schedules}
jobs:
  noop:
    runs-on: ubuntu-latest
    timeout-minutes: 1
    steps:
      - run: 'echo "schedule=${{{{ github.event.schedule }}}}"'
"""

def render(name, schedules):
    lines = []
    for s in schedules:
        lines.append(f"    - cron: '{s['cron']}'")
        if "timezone" in s:
            lines.append(f"      timezone: '{s['timezone']}'")
    return TEMPLATE.format(name=name, schedules="\n".join(lines))

if __name__ == "__main__":
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    for name, schedules in VARIANTS:
        (OUT / f"{name}.yml").write_text(render(name, schedules))
    print(f"wrote {len(VARIANTS)} workflows to {OUT}")
